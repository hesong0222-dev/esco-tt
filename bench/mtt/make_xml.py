"""Write MultiTypeTree (BEAST 2.7.7 + MTT 8.3.0) XMLs for the fixed trees of the MTT comparison.

Tree topology and node times are fixed: only migration-history operators (NodeRetype, TypeMergeSplit,
TypePairBirthDeath, TypeBirthDeath for d >= 3) and parameter operators (scale, up/down) are used.
No MultiTypeUniform / NodeShiftRetype / MultiTypeTreeScale / STX / TWB (they move node heights or topology).
Placeholders filled by the kernel: CHAINLENGTH, LOGEVERY, TREEEVERY.

usage: .venv/bin/python bench/mtt/make_xml.py   -> bench/mtt/xml/<tree>.xml
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402


def newick(tree):
    t = {}
    kids = {}
    for ev in tree["events"]:
        t[ev["id"] if ev["type"] == "sample" else ev["new"]] = ev["t"]
        if ev["type"] == "coal":
            kids[ev["new"]] = (ev["a"], ev["b"])
    root = tree["events"][-1]["new"]

    def rec(v, parent_t):
        bl = "" if parent_t is None else ":" + repr(parent_t - t[v])
        if v in kids:
            a, b = kids[v]
            return "(" + rec(a, t[v]) + "," + rec(b, t[v]) + ")" + bl
        return f"t{v}" + bl
    return rec(root, None) + ";"


def xml(name):
    tree = C.load_tree(name)
    d = len(tree["Ne"])
    od = C.offdiag(d)
    leaves = [ev for ev in tree["events"] if ev["type"] == "sample"]
    assert min(ev["t"] for ev in leaves) == 0.0
    taxa = "\n".join(f'      <taxon spec="Taxon" id="t{ev["id"]}"/>' for ev in leaves)
    traits = ",\n".join(f't{ev["id"]}=d{ev["deme"]}' for ev in leaves)
    types = ",".join(f"d{a}" for a in range(d))
    ne0 = " ".join(repr(float(x)) for x in tree["Ne"])
    m0 = " ".join(repr(float(tree["M"][a][b])) for a, b in od)
    tbd = (f'    <operator spec="TypeBirthDeath" id="TBD" weight="10" multiTypeTree="@tree" migrationModel="@migModel"/>\n'
           if d >= 3 else "")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- MTT comparison, tree {name} (sim/data/{name}.json). Generated by bench/mtt/make_xml.py. -->
<beast version="2.7" namespace="beast.base.core:beast.base.evolution.alignment:beast.base.inference:beast.base.inference.parameter:beast.base.inference.distribution:beast.base.inference.operator:beast.base.evolution.tree:beast.base.evolution.operator:beast.base.evolution:multitypetree.evolution.tree:multitypetree.distributions:multitypetree.operators:multitypetree.util">

  <taxa spec="TaxonSet" id="taxa">
{taxa}
  </taxa>

  <typeTraitSet spec="TraitSet" id="typeTraitSet" traitname="type" taxa="@taxa" value="
{traits}"/>

  <typeSet spec="multitypetree.evolution.tree.TypeSet" id="typeSet" value="{types}"/>

  <!-- backward-time rates, off-diagonal a-major order: {' '.join(f'M{a}{b}' for a, b in od)}; pair coalescence rate 1/popSize -->
  <migrationModel spec="multitypetree.evolution.tree.SCMigrationModel" id="migModel" typeSet="@typeSet">
    <rateMatrix spec="RealParameter" id="rateMatrix" dimension="{d*(d-1)}" value="{m0}"/>
    <popSizes spec="RealParameter" id="popSizes" dimension="{d}" value="{ne0}"/>
  </migrationModel>

  <run spec="MCMC" id="mcmc" chainLength="CHAINLENGTH" storeEvery="100000">

    <init spec="multitypetree.evolution.tree.MultiTypeTreeFromUntypedNewick" id="tree" typeLabel="type"
          adjustTipHeights="false" value="{newick(tree)}">
      <migrationModel spec="multitypetree.evolution.tree.SCMigrationModel" typeSet="@typeSet">
        <rateMatrix spec="RealParameter" dimension="{d*(d-1)}" value="{m0}"/>
        <popSizes spec="RealParameter" dimension="{d}" value="{ne0}"/>
      </migrationModel>
      <trait idref="typeTraitSet"/>
      <typeSet idref="typeSet"/>
    </init>

    <state>
      <stateNode idref="tree"/>
      <stateNode idref="rateMatrix"/>
      <stateNode idref="popSizes"/>
    </state>

    <distribution spec="CompoundDistribution" id="posterior">
      <distribution spec="StructuredCoalescentTreeDensity" id="treePrior">
        <multiTypeTree idref="tree"/>
        <migrationModel idref="migModel"/>
      </distribution>
      <distribution spec="CompoundDistribution" id="parameterPriors">
        <distribution spec="Prior" x="@popSizes">
          <distr spec="LogNormalDistributionModel" M="{C.NE_MU}" S="{C.NE_S}" meanInRealSpace="false"/>
        </distribution>
        <distribution spec="Prior" x="@rateMatrix">
          <distr spec="LogNormalDistributionModel" M="{C.M_MU}" S="{C.M_S}" meanInRealSpace="false"/>
        </distribution>
      </distribution>
    </distribution>

    <operator spec="ScaleOperator" id="RateScaler" parameter="@rateMatrix" scaleFactor="0.7" weight="{3*d*(d-1)}"/>
    <operator spec="ScaleOperator" id="PopSizeScaler" parameter="@popSizes" scaleFactor="0.7" weight="{3*d}"/>
    <operator spec="UpDownOperator" id="upDown" scaleFactor="0.8" weight="2">
      <up idref="popSizes"/>
      <down idref="rateMatrix"/>
    </operator>

    <operator spec="NodeRetype" id="NR" weight="10" multiTypeTree="@tree" migrationModel="@migModel"/>
    <operator spec="TypeMergeSplit" id="TMS" weight="10" multiTypeTree="@tree" migrationModel="@migModel" includeRoot="true"/>
    <operator spec="TypePairBirthDeath" id="TPBD" weight="10" multiTypeTree="@tree" migrationModel="@migModel"/>
{tbd}
    <logger id="tracelog" logEvery="LOGEVERY" fileName="$(filebase).log">
      <log idref="posterior"/>
      <log idref="treePrior"/>
      <log idref="popSizes"/>
      <log idref="rateMatrix"/>
      <log spec="TreeRootTypeLogger" multiTypeTree="@tree"/>
      <log spec="TypeChangeCounts" multiTypeTree="@tree" migrationModel="@migModel" id="typeChangeCounts"/>
      <log spec="beast.base.evolution.Sum" arg="@typeChangeCounts" id="totalTypeChanges"/>
    </logger>
    <logger id="treelog" logEvery="TREEEVERY" fileName="$(filebase).trees" mode="tree">
      <log idref="tree"/>
    </logger>
    <logger id="screenlog" logEvery="LOGEVERY">
      <log idref="posterior"/>
      <log idref="totalTypeChanges"/>
    </logger>
  </run>
</beast>
"""


if __name__ == "__main__":
    od = os.path.join(C.HERE, "xml")
    os.makedirs(od, exist_ok=True)
    for n in C.TREES:
        open(os.path.join(od, n + ".xml"), "w").write(xml(n))
        print("wrote", n)
