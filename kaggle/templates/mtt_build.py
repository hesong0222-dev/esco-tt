"""Bundle the MTT-comparison code into a self-contained Kaggle script.
usage: python3 kaggle/mtt/build.py MODE OUTDIR   (MODE smoke|full) -> OUTDIR/run.py
The script recreates esco/{dense,approx,bench/mtt,sim/data} under /kaggle/working/esco and runs kernel_main.py MODE."""
import base64, glob, gzip, json, os, sys
ESCO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ESCO, "bench", "mtt"))
import common as C
mode, outdir = sys.argv[1], sys.argv[2]
files = ["dense/esco_dense.py", "approx/mascot.py", "bench/mtt/common.py", "bench/mtt/typed_density.py",
         "bench/mtt/kernel_main.py"] + [f"bench/mtt/xml/{t}.xml" for t in C.TREES] + [f"sim/data/{t}.json" for t in C.TREES]
blob = {f: base64.b64encode(gzip.compress(open(os.path.join(ESCO, f), "rb").read())).decode() for f in files}
os.makedirs(outdir, exist_ok=True)
open(os.path.join(outdir, "run.py"), "w").write(f'''# generated by kaggle/mtt/build.py ({mode}); see bench/mtt_compare.md
import base64, gzip, os, subprocess, sys
FILES = {json.dumps(blob)}
root = "/kaggle/working/esco"
for f, b in FILES.items():
    p = os.path.join(root, f); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "wb").write(gzip.decompress(base64.b64decode(b)))
sys.exit(subprocess.call([sys.executable, os.path.join(root, "bench/mtt/kernel_main.py"), "{mode}"]))
''')
print("wrote", os.path.join(outdir, "run.py"), len(files), "files")
